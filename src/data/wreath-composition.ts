import type { BotanicalCategory, BotanicalId } from '@/data/botanical-assets';

export type WreathLayer = {
  id: string;
  assetId: BotanicalId;
  category: BotanicalCategory;
  x: number;
  y: number;
  startX: number;
  startY: number;
  rotation: number;
  startRotation: number;
  width: number;
  z: number;
  delay: number;
  duration: number;
  depth: number;
  desktopOnly?: boolean;
};

function layer(
  id: string,
  assetId: BotanicalId,
  category: BotanicalCategory,
  x: number,
  y: number,
  rotation: number,
  width: number,
  z: number,
  delay: number,
  duration: number,
  depth: number,
  travel: number,
  spin: number,
  desktopOnly = false,
): WreathLayer {
  const dx = x - 500;
  const dy = y - 508;
  const length = Math.hypot(dx, dy) || 1;
  return {
    id,
    assetId,
    category,
    x,
    y,
    startX: Math.round(x + (dx / length) * travel),
    startY: Math.round(y + (dy / length) * travel),
    rotation,
    startRotation: rotation + spin,
    width,
    z,
    delay,
    duration,
    depth,
    desktopOnly,
  };
}

